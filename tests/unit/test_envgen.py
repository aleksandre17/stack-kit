"""Env files are generated from the configuration catalogue (ADR-001 amendment 16.8): the committed
.env.example is a projection of it; `extend env` makes the ignored .env.<env> once -- non-secret
values filled, a SECRET pending (config reports it, a deploy refuses it), a generated key a fresh
value never printed, a data source an environment has none of the unroutable sentinel. Fixture
values only."""
from __future__ import annotations

import json
import os

import pytest

from delivery_host import commit, ctx_for, host, manifest_of, packaged, server
from lib import config_keys, config_policy, data_sources, envgen, identity, projections
from lib.delivery import release, running
from lib.delivery.context import DeliveryError
from lib.delivery.model import module_services

CATALOGUE = {"version": 1, "keys": [
    {"key": "App:PublicUrl", "sensitivity": "PUBLIC", "owner": "app", "allowedSource": "env file",
     "default": "https://shop.example.test"},
    {"key": "App:LogLevel", "sensitivity": "INTERNAL", "owner": "app", "allowedSource": "env file",
     "environments": {"dev": "Debug", "prod": "Warning"}},
    {"key": "Smtp:Password", "sensitivity": "SECRET", "owner": "app", "allowedSource": "secret store", "rotation": "yearly"},
    {"key": "Jwt:SigningKey", "sensitivity": "SECRET", "owner": "app", "allowedSource": "generated", "rotation": "on leak",
     "generate": "random:48"},
    {"key": "ConnectionStrings:Reports", "sensitivity": "SECRET", "owner": "app", "allowedSource": "secret store",
     "rotation": "yearly", "dataSource": True, "environments": {"dev": "none", "staging": "none"}},
    {"key": "Other:Only", "sensitivity": "PUBLIC", "owner": "x", "allowedSource": "env file", "default": "1",
     "policy": {"modules": ["elsewhere"]}},
]}


@pytest.fixture
def project(tmp_path, monkeypatch):
    root = host(tmp_path)
    (root / "ops" / "config" / "keys.json").write_text(json.dumps(CATALOGUE), encoding="utf-8")
    m = manifest_of(root)
    m["config"] = {"keys": "ops/config/keys.json"}
    (root / identity.MANIFEST_FILENAME).write_text(json.dumps(m), encoding="utf-8")
    commit(root, "with a catalogue")
    monkeypatch.setenv(identity.env_name("PROJECT_ROOT"), str(root))
    monkeypatch.chdir(root)
    return root


def test_the_env_example_is_a_projection_of_the_catalogue(project):
    projections.write(project, manifest_of(project))
    text = (project / "ops/config/edge/.env.example").read_text(encoding="utf-8")
    assert text.startswith(f"# generated by {identity.KIT_NAME} from ops/config/keys.json -- edit those, not this\n")
    assert "App__PublicUrl=https://shop.example.test\n" in text and "Smtp__Password=\n" in text
    assert "Jwt__SigningKey=\n" in text and "generated (48 random bytes)" in text
    assert "per environment: dev=Debug, prod=Warning" in text and "Other__Only" not in text
    m = manifest_of(project)
    cat = json.loads((project / "ops/config/keys.json").read_text(encoding="utf-8"))
    cat["keys"][0]["default"] = "https://shop2.example.test"
    (project / "ops/config/keys.json").write_text(json.dumps(cat), encoding="utf-8")
    errors, _ = projections.drift(project, m)
    assert any("ops/config/edge/.env.example" in e for e in errors), "a hand edit or a changed catalogue is drift"


def test_extend_env_fills_what_it_may_and_marks_what_only_the_host_may(project):
    said = envgen.make(project, manifest_of(project), "edge", "prod")
    f = project / "ops/config/edge/.env.prod"
    values = dict(line.split("=", 1) for line in f.read_text(encoding="utf-8").splitlines() if "=" in line and not line.startswith("#"))
    assert values["App__PublicUrl"] == "https://shop.example.test" and values["App__LogLevel"] == "Warning"
    assert envgen.PENDING.fullmatch(values["Smtp__Password"]) and envgen.PENDING.fullmatch(values["ConnectionStrings__Reports"])
    assert len(values["Jwt__SigningKey"]) >= 64 and values["Jwt__SigningKey"] not in " ".join(said), "never printed"
    assert "Other__Only" not in values
    if os.name == "posix":
        assert (f.stat().st_mode & 0o777) == 0o600
    assert envgen.make(project, manifest_of(project), "edge", "prod")[0].endswith("not overwritten")


def test_a_data_source_an_environment_has_none_of_is_the_sentinel_and_never_shared(project):
    for env in ("dev", "staging"):
        (project / f"ops/config/edge/.env.{env}").unlink()
        envgen.make(project, manifest_of(project), "edge", env)
    text = (project / "ops/config/edge/.env.dev").read_text(encoding="utf-8")
    assert f"ConnectionStrings__Reports={envgen.NONE_VALUE}\n" in text
    assert data_sources.is_sentinel(data_sources.identity(envgen.NONE_VALUE))
    cat = json.loads((project / "ops/config/keys.json").read_text(encoding="utf-8"))
    assert data_sources.shared(project, manifest_of(project), cat, ["dev", "staging", "prod"]) == []


def test_config_reports_a_pending_secret_and_a_deploy_refuses_it(project, tmp_path):
    envgen.make(project, manifest_of(project), "edge", "prod")
    values = (project / "ops/config/edge/.env.prod").read_text(encoding="utf-8")
    from lib import envfile

    found = config_policy.problems(CATALOGUE, envfile.parse(project / "ops/config/edge/.env.prod"), folder="edge", environment="prod")
    assert any("Smtp__Password is pending" in f for f in found)
    assert not any(v in " ".join(found) for v in values.split() if v.startswith("Jwt__SigningKey="))
    (project / "ops/config/edge/.env.staging").unlink()
    envgen.make(project, manifest_of(project), "edge", "staging")
    with pytest.raises(DeliveryError, match="pending") as e:
        release.release(ctx_for(project, server(tmp_path)), "edge", packaged(project))
    assert e.value.code == 4


def test_a_generated_key_never_ships_in_the_env_file_it_is_made_on_the_server(project, tmp_path):
    (project / "ops/config/edge/.env.staging").unlink()
    envgen.make(project, manifest_of(project), "edge", "staging")
    ctx = ctx_for(project, server(tmp_path))
    svc = module_services(ctx.manifest, "edge")[0]
    assert running.generated(ctx, svc) == {"Jwt__SigningKey": 48}
    assert b"Jwt__SigningKey" not in running.env_file(ctx, svc)


def test_extend_env_refuses_a_file_git_would_track_and_a_secret_with_a_per_environment_value(project):
    (project / "ops/config/.gitignore").write_text("!*\n", encoding="utf-8")
    with pytest.raises(envgen.EnvGenError, match="not be ignored"):
        envgen.make(project, manifest_of(project), "edge", "prod")
    cat = json.loads((project / "ops/config/keys.json").read_text(encoding="utf-8"))
    cat["keys"][2]["environments"] = {"prod": "fixture-value"}
    (project / "ops/config/keys.json").write_text(json.dumps(cat), encoding="utf-8")
    verdict = config_keys.check(project, manifest_of(project))
    assert any("per-environment value -- a committed secret" in f for f in verdict.failures)
