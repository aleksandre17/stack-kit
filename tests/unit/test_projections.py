"""What a deploy runs, visible in the host as generated projections (ADR-001 amendment 16.7): the
effective recipe of each deployable module and each environment's stack compose, each under a header
naming its sources; validate reports a stale one; a release refuses one; the release id and the
artifact's name are the only symbolic parts. The fixture's driver is the host's own (the kit ships
none of it)."""
from __future__ import annotations

import json

import pytest

from delivery_host import commit, ctx_for, host, manifest_of, packaged, server
from lib import identity, projections
from lib.delivery import release
from lib.delivery.context import DeliveryError


@pytest.fixture
def project(tmp_path, monkeypatch):
    root = host(tmp_path)
    monkeypatch.setenv(identity.env_name("PROJECT_ROOT"), str(root))
    monkeypatch.chdir(root)
    return root


def test_render_writes_the_effective_recipe_and_each_environments_compose(project):
    said = projections.write(project, manifest_of(project))
    recipe = (project / "ops/containers/edge/Dockerfile").read_text(encoding="utf-8")
    first, rest = recipe.split("\n", 1)
    assert first.startswith(f"# generated by {identity.KIT_NAME} from drivers/fixture-svc/Recipe.tpl")
    assert first.endswith("-- edit those, not this")
    assert rest.startswith("FROM fixture/run:7\n") and "COPY out/*.bin /app.bin" in rest and "ENV HOME=${HOME}" in rest
    for env in ("dev", "staging", "prod"):
        text = (project / f"ops/compose/stack/{env}/compose.yml").read_text(encoding="utf-8")
        doc = json.loads(text.split("\n", 1)[1])
        assert doc["name"].startswith("shop-") and env in doc["name"]
        assert doc["services"]["edge"]["image"].endswith(projections.RELEASE)
    assert any(line.startswith("write ops/compose/stack/staging/compose.yml") for line in said)
    assert all(line.startswith("unchanged") for line in projections.write(project, manifest_of(project))), "idempotent"


def test_validate_reports_a_projection_its_sources_no_longer_render(project):
    assert projections.drift(project, manifest_of(project))[1], "not rendered yet: a notice"
    projections.write(project, manifest_of(project))
    assert projections.drift(project, manifest_of(project)) == ([], [])
    m = manifest_of(project)
    m["modules"]["edge"]["toolchain"]["version"] = "8"
    (project / identity.MANIFEST_FILENAME).write_text(json.dumps(m), encoding="utf-8")
    errors, _ = projections.drift(project, m)
    assert len(errors) == 1 and "ops/containers/edge/Dockerfile" in errors[0] and "never the projection" in errors[0]


def test_a_release_ships_what_was_rendered_and_refuses_a_stale_projection(project, tmp_path):
    projections.write(project, manifest_of(project))
    commit(project, "rendered")
    t = server(tmp_path)
    assert release.release(ctx_for(project, t), "edge", packaged(project)) == 0
    m = manifest_of(project)
    m["modules"]["edge"]["toolchain"]["version"] = "8"
    (project / identity.MANIFEST_FILENAME).write_text(json.dumps(m), encoding="utf-8")
    commit(project, "a new toolchain, not rendered")
    with pytest.raises(DeliveryError, match="projection is stale") as e:
        release.release(ctx_for(project, server(tmp_path / "2")), "edge", packaged(project))
    assert e.value.code == 5 and "ops/containers/edge/Dockerfile" in str(e.value)


def test_a_hand_edited_compose_projection_is_refused_by_the_release(project, tmp_path):
    projections.write(project, manifest_of(project))
    f = project / "ops/compose/stack/staging/compose.yml"
    head, body = f.read_text(encoding="utf-8").split("\n", 1)
    doc = json.loads(body)
    doc["services"]["edge"]["restart"] = "no"
    f.write_text(head + "\n" + json.dumps(doc, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    commit(project, "edited by hand")
    with pytest.raises(DeliveryError, match="compose this release writes differs"):
        release.release(ctx_for(project, server(tmp_path)), "edge", packaged(project))


def test_a_host_without_projections_releases_as_before(project, tmp_path):
    assert release.release(ctx_for(project, server(tmp_path)), "edge", packaged(project)) == 0
