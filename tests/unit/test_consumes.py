"""What a project uses from a shared platform it does not own (ADR-001 amendment 17): a fixture
project consumes a fixture platform's network, an endpoint and an edge route. Its compose joins the
network as external and is given the endpoint; a deploy never creates nor removes that network; the
preflight reads it on the recorded server (present: a notice; missing: NOT RUN with the owner's
action, the plan included); the routes are a projection the platform's owner applies, drift-checked;
validate names a consumption the declarations cannot answer."""
from __future__ import annotations

import json

import pytest

from delivery_host import ROOT, ctx_for, host, manifest_of, packaged, server
from lib import identity, projections
from lib.delivery import consumes, manage, model, release, running
from lib.delivery.context import DeliveryError

PLATFORM_NET = "platform-net"
CONSUMES = {"networks": {"platform": {"services": ["edge"], "owner": "the platform project"}},
            "endpoints": {"telemetry": {"env": "TELEMETRY_ENDPOINT", "services": ["edge"]}},
            "routes": [{"environment": "staging", "host": "shop.staging.example.test", "service": "edge", "tls": "required"},
                       {"environment": "staging", "path": "/shop", "service": "edge", "tls": "required"}]}
GIVEN = {"networks": {"platform": PLATFORM_NET},
         "endpoints": {"telemetry": {e: f"http://collector.{e}.invalid:4318" for e in ("dev", "staging", "prod")}}}
ROUTES = "ops/compose/stack/staging/edge-routes.json"


@pytest.fixture
def project(tmp_path, monkeypatch):
    root = host(tmp_path, target_extra={"consumes": GIVEN}, manifest_extra={"consumes": CONSUMES})
    monkeypatch.setenv(identity.env_name("PROJECT_ROOT"), str(root))
    monkeypatch.chdir(root)
    return root


def _ran(t) -> list[tuple]:
    return [e[1] for e in t.log if e[0] == "exec"]


def test_the_compose_joins_the_platform_network_as_external_and_is_given_the_endpoint(project):
    projections.write(project, manifest_of(project))
    doc = json.loads((project / "ops/compose/stack/staging/compose.yml").read_text(encoding="utf-8").split("\n", 1)[1])
    edge = doc["services"]["edge"]
    assert edge["networks"] == ["default", PLATFORM_NET]
    assert doc["networks"][PLATFORM_NET] == {"name": PLATFORM_NET, "external": True}
    assert edge["environment"]["TELEMETRY_ENDPOINT"] == "http://collector.staging.invalid:4318"


def test_the_routes_are_a_projection_the_platforms_owner_applies(project):
    projections.write(project, manifest_of(project))
    doc = json.loads((project / ROUTES).read_text(encoding="utf-8"))
    assert doc["generated"].startswith(f"generated by {identity.KIT_NAME} from {identity.MANIFEST_FILENAME} consumes.routes")
    assert doc["generated"].endswith("-- edit those, not this")
    assert (doc["project"], doc["environment"], doc["target"]) == ("shop", "staging", "box")
    upstream = {"service": "edge", "container": "shop-staging-edge", "port": 9000, "network": PLATFORM_NET}
    assert doc["routes"] == [{"path": "/shop", "tls": "required", "upstream": upstream},
                             {"host": "shop.staging.example.test", "path": "/", "tls": "required", "upstream": upstream}]
    assert not (project / "ops/compose/stack/dev/edge-routes.json").exists(), "an environment without routes has none"


def test_a_route_projection_its_sources_no_longer_render_is_drift(project):
    projections.write(project, manifest_of(project))
    assert projections.drift(project, manifest_of(project)) == ([], [])
    m = manifest_of(project)
    m["consumes"]["routes"][0]["host"] = "shop.example.test"
    (project / identity.MANIFEST_FILENAME).write_text(json.dumps(m), encoding="utf-8")
    errors, _ = projections.drift(project, m)
    assert len(errors) == 1 and ROUTES in errors[0] and "never the projection" in errors[0]


def test_a_present_platform_network_is_read_never_created(project, tmp_path):
    t = server(tmp_path, networks=[PLATFORM_NET])
    said: list[str] = []
    ctx = ctx_for(project, t)
    ctx.out = said.append
    assert release.release(ctx, "edge", packaged(project)) == 0
    ran = _ran(t)
    assert ("eng", "network", "inspect", PLATFORM_NET) in ran
    assert not [a for a in ran if a[1:3] in (("network", "create"), ("network", "rm")) and PLATFORM_NET in a]
    assert ("eng", "network", "create", "shop-staging") in ran, "this project's own network is still its own"
    assert f"[preflight] consumes: network {PLATFORM_NET} (platform) is there" in said
    t.exec(["eng", "network", "rm", PLATFORM_NET])  # the platform's owner took it down
    t.log.clear()
    running.regenerate(ctx_for(project, t))
    assert not [a for a in _ran(t) if a[1:3] == ("network", "create")], "a regenerate never creates the platform's"
    assert manage.nuke(ctx_for(project, t)) == 0
    assert not [a for a in _ran(t) if a[1:3] == ("network", "rm") and PLATFORM_NET in a], "nuke never removes it"


def test_a_missing_platform_network_is_not_run_with_its_owners_action(project, tmp_path):
    archive = packaged(project)
    for planned in (True, False):
        t = server(tmp_path / str(planned))
        ctx = ctx_for(project, t)
        with pytest.raises(DeliveryError) as e:
            release.release(ctx.dry() if planned else ctx, "edge", archive)
        text = str(e.value)
        assert e.value.code == 4 and text.startswith("NOT RUN:") and "never creates" in text
        assert f"network {PLATFORM_NET} (consumes.networks.platform, joined by edge) is not on target box" in text
        assert f"the platform project provides it there (`eng network create {PLATFORM_NET}`" in text
        assert not [a for a in _ran(t) if a[1:3] == ("network", "create")], "nothing is created"
        assert not t.exists(f"{ROOT}/shop/staging/stack/compose.yml")


def test_a_project_that_consumes_nothing_checks_nothing(tmp_path, monkeypatch):
    root = host(tmp_path)
    monkeypatch.chdir(root)
    assert consumes.check(ctx_for(root, server(tmp_path))) == []
    assert consumes.uses(manifest_of(root), {}, "staging", "edge") == consumes.Uses()


def test_validate_names_what_the_declarations_cannot_answer(project):
    m = manifest_of(project)
    services = {s.id: s for s in model.all_services(m)}
    envs = ["dev", "staging", "prod"]
    data = json.loads((project / "ops/deploy/targets.json").read_text(encoding="utf-8"))
    assert consumes.problems(m, data, envs, services, "shop") == []
    m["consumes"]["networks"]["platform"]["services"].append("ghost")
    m["consumes"]["routes"].append({"environment": "qa", "service": "edge", "tls": "required"})
    box = data["targets"]["box"]["consumes"]
    del box["networks"]["platform"]
    box["networks"]["stray"] = "shop-staging-mine"
    box["endpoints"]["telemetry"]["prod"] = "http://user:hunter2@collector.invalid"
    said = "\n".join(consumes.problems(m, data, envs, services, "shop"))
    assert "consumes.networks.platform.services: 'ghost' is not a service this project deploys" in said
    assert "consumes.routes[2].environment: 'qa' is not a declared environment" in said
    assert "consumes.routes[2]: a route names its `host`, its `path` prefix, or both" in said
    assert "targets.box.consumes.networks.platform: required -- staging deploys there and consumes it" in said
    assert "targets.box.consumes.networks.stray: no `consumes.networks.stray` in the manifest" in said
    assert "targets.box.consumes.endpoints.telemetry.prod: the address carries a credential" in said
    assert "hunter2" not in said, "a finding never prints the value"
    data["targets"]["box"]["consumes"]["networks"] = {"platform": "shop-staging-mine"}
    assert any("in this project's own namespace" in p for p in consumes.problems(m, data, envs, services, "shop"))
