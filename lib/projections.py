"""What a deploy runs, made visible in the host as GENERATED projections (ADR-001 amendment 16.7).

The effective container recipe of a module lives in its driver (a template rendered with the
module's values) and the environment's stack compose is rendered on the server at deploy, so a host
could not read either. `render` writes both into the host, each under a one-line header naming its
sources ("edit those, not this"):

    containers   each deployable module's effective Dockerfile -- its own `container.dockerfile`, or
                 its driver's template (a host's driver from `extend driver` included) rendered for it
                 (default `ops/containers/{module}/Dockerfile`; `Dockerfile.<service>` for a second one)
    stack        each environment's stack compose as deploy writes it on its target
                 (default `ops/compose/stack/{environment}/compose.yml`)

The manifest, the driver and the targets stay the one source; the files are projections. Two values
are known only when a commit is packaged, and are written symbolically: the release id
(`{release}`, also the revision label) and the packaged artifact's file name (the driver's declared
`container.artifact` glob). Everything else is the bytes deploy ships. A credential is the one the
module declares (`credentials`), not whatever this machine's secrets folder holds.

`validate` reports a projection that differs from what its sources render (an error) or is not
rendered yet (a notice); a release refuses (exit 5) when a committed projection is stale -- its
recipe is compared with the archive's, its services with the documents the release is about to write.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from lib import identity

RELEASE = "{release}"
DEFAULTS = {"containers": "ops/containers/{module}/Dockerfile", "stack": "ops/compose/stack/{environment}/compose.yml"}


def header(sources: list[str]) -> str:
    return f"# generated by {identity.KIT_NAME} from {', '.join(sources)} -- edit those, not this\n"


def body(data: bytes) -> bytes:
    """A projection without its header line."""
    first, _, rest = data.partition(b"\n")
    return rest if first.startswith(b"# generated by ") else data


def place(manifest: dict[str, Any], kind: str, **values: str) -> str:
    tpl = str(((manifest.get("projections") or {}).get(kind)) or DEFAULTS[kind])
    for k, v in values.items():
        tpl = tpl.replace("{" + k + "}", v)
    return tpl


# ── containers ───────────────────────────────────────────────────────────────

def _build_services(manifest: dict[str, Any], unrenderable: list[str]) -> list[Any]:
    from lib.delivery.model import deployable, module_services

    out = []
    for mid in (manifest.get("modules") or {}):
        try:
            if deployable(manifest, mid):
                out += [s for s in module_services(manifest, mid) if s.kind == "build"]
        except (ValueError, KeyError, TypeError) as e:  # a broken declaration: validate reports it elsewhere
            unrenderable.append(f"modules.{mid}: {e}")
    return out


def container_path(manifest: dict[str, Any], service: Any) -> str:
    from lib.delivery.model import module_services

    builds = [s for s in module_services(manifest, service.module) if s.kind == "build"]
    rel = place(manifest, "containers", module=str(service.module), service=service.id)
    return rel if builds and builds[0].id == service.id else f"{rel}.{service.id}"


def recipe_sources(root: Path, manifest: dict[str, Any], service: Any) -> list[str]:
    from lib.delivery.model import driver_home

    cfg = manifest["modules"][service.module]
    if service.spec.get("dockerfile"):
        return [f"{cfg['path']}/{service.spec['dockerfile']}"]
    tpl = driver_home(service.driver) / str(service.spec.get("template") or "")
    try:
        shown = tpl.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        shown = f"{identity.KIT_NAME} drivers/{service.driver}/{service.spec.get('template')}"
    return [shown, f"{identity.MANIFEST_FILENAME} modules.{service.module}"]


def recipe(root: Path, manifest: dict[str, Any], service: Any) -> bytes:
    """The service's effective recipe with the artifact written as its declared glob."""
    from lib import package

    return package.recipe(root, manifest, service, {}, artifact=str(service.spec.get("artifact") or ""))["Dockerfile"]


def symbolic_recipe(shipped: bytes, service: Any, tree: dict[str, Any]) -> bytes:
    """An archive's recipe in projection form: its concrete artifact name back to the declared glob."""
    from lib import package

    pattern = str(service.spec.get("artifact") or "")
    if not pattern or service.spec.get("dockerfile"):
        return shipped
    concrete = package._artifact(tree, service.spec, service.id)
    return shipped.replace(concrete.encode("utf-8"), pattern.encode("utf-8")) if concrete else shipped


# ── the stack compose ────────────────────────────────────────────────────────

def _context(root: Path, manifest: dict[str, Any], environment: str):
    """A delivery context that reaches nothing (a recording transport): places and commands only."""
    from lib.delivery.context import DeliveryError, open_delivery
    from lib.delivery.transport import RecordingTransport

    try:
        return open_delivery(root, manifest, environment=environment, transport=RecordingTransport(), out=lambda _l: None)
    except (DeliveryError, ValueError):
        return None


def service_doc(ctx, service: Any, release: str, credentials: list[str] | None = None) -> dict[str, Any]:
    """The service's compose document for `release`; its credentials the declared ones unless given."""
    from lib.delivery import running, stack

    state = stack.State(release=release if service.module else None)
    creds = credentials if credentials is not None else (
        sorted({Path(str(c["file"])).name for c in service.credentials}) if service.module else [])
    return stack.service_document(service, project=ctx.project, environment=ctx.environment, target=ctx.target,
                                  places=ctx.places, state=state, revision=release if service.module else "",
                                  credentials=creds, env_file=bool(service.secrets_folder),
                                  generated=sorted(running.generated(ctx, service)) if service.module else [])


def compose(ctx) -> bytes:
    from lib.delivery import running, stack

    docs = {s.id: service_doc(ctx, s, RELEASE) for s in running.services(ctx)}
    return stack.render(stack.compose_document(project=ctx.project, environment=ctx.environment, services=docs))


def stack_sources(manifest: dict[str, Any]) -> list[str]:
    return [identity.MANIFEST_FILENAME, str((manifest.get("deploy") or {}).get("targets") or "deploy targets"),
            "the drivers' registry"]


# ── all of them ──────────────────────────────────────────────────────────────

def rendered(root: Path, manifest: dict[str, Any], unrenderable: list[str] | None = None) -> dict[str, bytes]:
    """{host path: bytes} of every projection, header included; what cannot be rendered is said in
    `unrenderable` (a broken declaration other checks name), never raised."""
    from lib import catalogs

    said = unrenderable if unrenderable is not None else []
    out: dict[str, bytes] = {}
    for s in _build_services(manifest, said):
        try:
            out[container_path(manifest, s)] = header(recipe_sources(root, manifest, s)).encode("utf-8") + recipe(root, manifest, s)
        except (ValueError, KeyError, OSError) as e:
            said.append(f"{s.id}: {e}")
    if (manifest.get("deploy") or {}).get("targets"):
        try:
            envs = catalogs.ids("environments", manifest)
        except ValueError:
            envs = []
        for env in envs:
            ctx = _context(root, manifest, env)
            if ctx is None or not ctx.commands["compose"]:
                continue
            try:
                out[place(manifest, "stack", environment=env)] = header(stack_sources(manifest)).encode("utf-8") + compose(ctx)
            except (ValueError, KeyError, OSError) as e:
                said.append(f"{env} stack: {e}")
    return out


def write(root: Path, manifest: dict[str, Any], *, plan: bool = False) -> list[str]:
    said = []
    for rel, data in sorted(rendered(root, manifest).items()):
        f = root / rel
        if f.is_file() and f.read_bytes() == data:
            said.append(f"unchanged {rel}")
            continue
        said.append(f"{'plan: ' if plan else ''}write {rel}")
        if not plan:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_bytes(data)
    return said


def drift(root: Path, manifest: dict[str, Any]) -> tuple[list[str], list[str]]:
    """(errors: a committed projection its sources no longer render, notices: one not rendered yet)."""
    errors, notices, unrenderable = [], [], []
    for rel, data in sorted(rendered(root, manifest, unrenderable).items()):
        f = root / rel
        if not f.is_file():
            notices.append(f"projection {rel} is not rendered (`{identity.KIT_NAME} render`)")
        elif f.read_bytes().replace(b"\r\n", b"\n") != data:
            errors.append(f"projection {rel} differs from what its sources render -- edit the sources and run "
                          f"`{identity.KIT_NAME} render`, never the projection")
    notices += [f"projection not rendered: {u}" for u in unrenderable]
    return errors, notices


def release_problems(ctx, svc: list[Any], rid: str, trees: dict[str, dict[str, bytes]]) -> list[str]:
    """A committed projection the release would not match: the archive's recipe, or the service
    document the release is about to write (its release id back to `{release}`)."""
    out = []
    for s in svc:
        if s.kind == "build":
            f = ctx.root / container_path(ctx.manifest, s)
            shipped = (trees.get(s.id) or {}).get("Dockerfile")
            if f.is_file() and shipped is not None:
                if body(f.read_bytes().replace(b"\r\n", b"\n")) != symbolic_recipe(shipped, s, trees[s.id]):
                    out.append(f"{s.id}: the recipe this release ships differs from {f.relative_to(ctx.root).as_posix()}")
    f = ctx.root / place(ctx.manifest, "stack", environment=ctx.environment)
    if f.is_file():
        try:
            committed = json.loads(body(f.read_bytes()))
        except ValueError:
            return out + [f"{f.relative_to(ctx.root).as_posix()}: not a rendered stack compose"]
        for s in svc:
            want = (committed.get("services") or {}).get(s.id)
            from lib.delivery import running

            actual = service_doc(ctx, s, rid, sorted(running.credential_files(ctx, s)))
            have = json.loads(json.dumps(actual).replace(json.dumps(rid)[1:-1], RELEASE))
            if want != have:
                out.append(f"{s.id}: the compose this release writes differs from {f.relative_to(ctx.root).as_posix()} "
                           f"(re-render it; a credential file the secrets folder holds is declared in `credentials`)")
    return out
