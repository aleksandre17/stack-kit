"""Env files are the kit's job, generated from the configuration catalogue (ADR-001 amendment 16.8).

The catalogue (`config.keys`) is the one source of which keys a module reads; the files are made
from it, never by hand:

    .env.example   committed, a PROJECTION: every key of the folder, its sensitivity, which
                   environments require it, its default or per-environment values (never a secret's),
                   under the generated header -- `render` writes it, validate reports drift
    .env.<env>     ignored, made once by `extend env <folder> --env <env>` and never overwritten:
                   a PUBLIC or INTERNAL key's value for that environment (`environments.<env>`, else
                   its `default`), a SECRET as a pending marker (`config` reports it, a deploy refuses
                   it), a generated key (`policy.generate.bytes`, or `generate: "random:<bytes>"`) a
                   fresh random value written into the file and never printed, and a data source the
                   environment declares `none` the kit's unroutable sentinel

A key belongs to the folders its `policy.modules` names, else to every folder.
"""
from __future__ import annotations

import os
import re
import secrets
import subprocess
from pathlib import Path
from typing import Any

from lib import identity
from lib.config_policy import PENDING, generate_bytes  # noqa: F401 -- the one reader, re-exported

#: The value of a data source an environment declares `none`: a host under .invalid (RFC 2606) never
#: resolves, so a layered config file can never lead the application to a real store.
NONE_VALUE = "Server=none.invalid;Database=none"


class EnvGenError(ValueError):
    pass


def rows_for(catalogue: dict[str, Any], folder: str) -> list[dict[str, Any]]:
    out = []
    for row in catalogue.get("keys") or []:
        if not isinstance(row, dict) or not row.get("key"):
            continue
        mods = (row.get("policy") or {}).get("modules") if isinstance(row.get("policy"), dict) else None
        if not mods or folder in mods:
            out.append(row)
    return out


def _required_in(row: dict[str, Any], environments: list[str]) -> list[str]:
    req = (row.get("policy") or {}).get("required") if isinstance(row.get("policy"), dict) else None
    return [e for e in environments if e in req] if isinstance(req, list) else (list(environments) if req else [])


def _name(row: dict[str, Any]) -> str:
    from lib.config_policy import env_name

    return env_name(row)


def header(catalogue_rel: str) -> str:
    return f"# generated by {identity.KIT_NAME} from {catalogue_rel} -- edit those, not this\n"


def example(catalogue: dict[str, Any], catalogue_rel: str, folder: str, environments: list[str]) -> str:
    """The folder's committed .env.example: every key, described; a secret's value always empty."""
    lines = [header(catalogue_rel).rstrip("\n")]
    for row in rows_for(catalogue, folder):
        if "*" in str(row["key"]):
            # A family of keys (`A:B:*`) names no one variable: it is described, never assigned.
            member = _name({**row, "key": str(row["key"]).replace("*", "MEMBER")}).replace("MEMBER", "<Name>")
            lines.append(f"# {row['key']} -- {row.get('sensitivity') or '?'}; a family: set {member}=... per member")
            continue
        req = _required_in(row, environments)
        traits = [str(row.get("sensitivity") or "?"), f"required in {', '.join(req)}" if req else "optional"]
        if row.get("dataSource"):
            traits.append("a data source")
        if generate_bytes(row):
            traits.append(f"generated ({generate_bytes(row)} random bytes)")
        per_env = row.get("environments") if isinstance(row.get("environments"), dict) else {}
        if per_env and row.get("sensitivity") != "SECRET":
            traits.append("per environment: " + ", ".join(f"{e}={v}" for e, v in sorted(per_env.items())))
        elif per_env:
            traits.append("none in: " + ", ".join(e for e, v in sorted(per_env.items()) if v == "none"))
        lines.append(f"# {row['key']} -- {'; '.join(traits)}" + (f" -- {row['note']}" if row.get("note") else ""))
        value = "" if row.get("sensitivity") == "SECRET" or "default" not in row else str(row["default"])
        lines.append(f"{_name(row)}={value}")
    return "\n".join(lines) + "\n"


def value_for(row: dict[str, Any], environment: str, environments: list[str]) -> tuple[str | None, str]:
    """(the value an environment's file starts with, what it is: set | generated | none | pending | absent)."""
    per_env = row.get("environments") if isinstance(row.get("environments"), dict) else {}
    if environment in per_env:
        v = per_env[environment]
        if v == "none" and row.get("dataSource"):
            return NONE_VALUE, "none"
        if row.get("sensitivity") == "SECRET":
            raise EnvGenError(f"{row['key']}: a SECRET has no committed per-environment value (only `none` for a data source)")
        return str(v), "set"
    if generate_bytes(row):
        return secrets.token_urlsafe(generate_bytes(row)), "generated"
    declared = (row.get("policy") or {}).get("required") if isinstance(row.get("policy"), dict) else None
    if row.get("sensitivity") == "SECRET" and declared is not None and environment not in _required_in(row, environments):
        return None, "absent"  # a secret the key declares unneeded here is left unset, never asked for
    if row.get("sensitivity") == "SECRET":
        return f"<<pending: {row['key']} is a SECRET -- its value from the secret store>>", "pending"
    if "default" in row:
        return str(row["default"]), "set"
    if environment in _required_in(row, environments):
        return f"<<pending: {row['key']} is required in {environment}>>", "pending"
    return None, "absent"


def env_file(catalogue: dict[str, Any], catalogue_rel: str, folder: str, environment: str,
             environments: list[str]) -> tuple[str, dict[str, int]]:
    """(the text of an ignored .env.<environment>, a count of each kind of value)."""
    lines = [f"# made by `{identity.KIT_NAME} extend env {folder} --env {environment}` from {catalogue_rel}; "
             f"ignored -- fill each pending value, never commit this file"]
    counts: dict[str, int] = {}
    for row in rows_for(catalogue, folder):
        if "*" in str(row["key"]):
            continue  # a family names no one variable
        value, kind = value_for(row, environment, environments)
        counts[kind] = counts.get(kind, 0) + 1
        if value is not None:
            lines.append(f"{_name(row)}={value}")
    return "\n".join(lines) + "\n", counts


def _ignored(root: Path, path: Path) -> bool:
    ran = subprocess.run(["git", "-C", str(root), "check-ignore", "-q", str(path.relative_to(root).as_posix())],
                         capture_output=True, text=True)
    return ran.returncode == 0


def make(root: Path, manifest: dict[str, Any], folder: str, environment: str, *, plan: bool = False) -> list[str]:
    from lib import catalogs, config_policy
    from lib.project_context import ProjectContext

    if not folder or not environment:
        raise EnvGenError("name the folder and the environment: `extend env <folder> --env <id>`")
    envs = catalogs.ids("environments", manifest)
    catalogs.require("environments", environment, manifest, what="--env")
    catalogue = config_policy.catalogue_of(root, manifest)
    if not catalogue:
        raise EnvGenError("no configuration catalogue is declared (manifest `config.keys`): it is what an env file is made from")
    ctx = ProjectContext(root=root, manifest=manifest)
    if folder not in ctx.list_secrets_module_folders():
        raise EnvGenError(f"'{folder}' is no module's secrets folder ({', '.join(ctx.list_secrets_module_folders())})")
    target = ctx.secrets_root / folder / f".env.{environment}"
    rel = target.relative_to(root).as_posix()
    if target.exists():
        return [f"{rel}: already there -- not overwritten"]
    if (root / ".git").exists() and not _ignored(root, target):
        raise EnvGenError(f"{rel} would not be ignored by git -- an env file holds secrets; ignore it first")
    text, counts = env_file(catalogue, str((manifest.get("config") or {}).get("keys")), folder, environment, envs)
    summary = ", ".join(f"{n} {k}" for k, n in sorted(counts.items()))
    if plan:
        return [f"plan: create {rel} ({summary})"]
    target.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return [f"create {rel} ({summary}; mode 600; no value printed)"]
